//! OT-2 v10.0.0 robot-server operations mapped onto a2a-lab logs, metrics, and tasks.

/// How an HTTP operation is advertised.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// Time-ordered event stream.
    Log,
    /// Numeric or 0/1 gauge.
    Metric,
    /// Mutation or object-valued read.
    Task,
    /// Flex-only or OT-2-unsupported; not advertised.
    Skip,
}

/// One robot-server operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Entry {
    /// a2a-lab identifier.
    pub id: &'static str,
    /// HTTP method.
    pub method: &'static str,
    /// Path template (`{runId}` style).
    pub path: &'static str,
    /// a2a-lab domain.
    pub kind: Kind,
    /// Human-readable name.
    pub name: &'static str,
    /// What the operation does.
    pub description: &'static str,
    /// Metric unit, empty otherwise.
    pub unit: &'static str,
}

