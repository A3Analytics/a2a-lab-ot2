/// Returns inventory rows of `kind`.
pub fn of_kind(kind: Kind) -> impl Iterator<Item = &'static Entry> {
    ENTRIES.iter().filter(move |entry| entry.kind == kind)
}

/// Looks up a non-skip task by id.
#[must_use]
pub fn task_entry(id: &str) -> Option<&'static Entry> {
    ENTRIES
        .iter()
        .find(|entry| entry.kind == Kind::Task && entry.id == id)
}

/// True when the row is a GET-backed task.
#[must_use]
pub fn is_read(entry: &Entry) -> bool {
    entry.kind == Kind::Task && entry.method == "GET"
}

/// True when this robot-server path is inventoried (including Flex skips).
#[must_use]
pub fn covers(method: &str, path: &str) -> bool {
    if method == "GET" && path == "/logs/{log_identifier}" {
        return of_kind(Kind::Log).any(|entry| entry.path.starts_with("/logs/"));
    }
    ENTRIES
        .iter()
        .any(|entry| entry.method == method && entry.path == path)
}
